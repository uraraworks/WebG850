/** 行×列の ASCII アート ('#'/'.' , 7行5列) を列方向 5 バイトへ変換する。 */
function rowsToColumns(rows: readonly string[]): Uint8Array {
  const cols = new Uint8Array(GLYPH_WIDTH);
  for (let x = 0; x < GLYPH_WIDTH; x++) {
    let byte = 0;
    for (let y = 0; y < GLYPH_HEIGHT; y++) {
      if (rows[y][x] === '#') {
        byte |= 1 << y; // bit0 = 最上段
      }
    }
    cols[x] = byte;
  }
  return cols;
}

const UNDEFINED_GLYPH = rowsToColumns(UNDEFINED_ROWS);

const glyphCache = new Map<number, Uint8Array>();

/**
 * コード（ASCII 0x20〜0x7E）から 5 バイトのグリフデータを返す。
 * 各バイトは 1 列分の縦 7 ドット（bit0 が最上段）。
 * 未定義のコードは空白ではなく全点灯の箱を返す（未実装を無言にしない方針）。
 */
export function getGlyph(code: number): Uint8Array {
  const cached = glyphCache.get(code);
  if (cached) return cached;

  const rows = GLYPH_ROWS[code];
  const data = rows ? rowsToColumns(rows) : UNDEFINED_GLYPH;
  glyphCache.set(code, data);
  return data;
}

export const FONT_GLYPH_WIDTH = GLYPH_WIDTH;
export const FONT_GLYPH_HEIGHT = GLYPH_HEIGHT;
